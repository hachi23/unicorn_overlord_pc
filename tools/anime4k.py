"""Turns the Anime4K mpv shaders (gpu/third_party/anime4k) into Vulkan compute shaders.

mpv runs each //!HOOK block as a pass over named textures; here every pass becomes one compute
shader, and the passes of a model form a table (anime4k_models.h) the presenter runs in order.
Each texture a pass binds is a sampled image; mpv's NAME_tex/_texOff/_pos/_size/_pt are macros.
The model's input arrives as the game image samples it (linear light from an sRGB view): with
push constant `linear` set it is encoded to sRGB on reading and the model's output decoded, as
Anime4K works on encoded values like video.

Run after changing the models or this script:  python3 tools/anime4k.py
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'gpu/third_party/anime4k'
SHADERS = ROOT / 'gpu/platform/shaders'
OUT = SHADERS / 'anime4k'
TABLE = ROOT / 'gpu/platform/anime4k_models.h'
# (name in the table, mpv file): the presets pick a restore and an upscale model by name.
MODELS = (('restore_s', 'Anime4K_Restore_CNN_S.glsl'), ('restore_m', 'Anime4K_Restore_CNN_M.glsl'),
          ('upscale_s', 'Anime4K_Upscale_CNN_x2_S.glsl'), ('upscale_m', 'Anime4K_Upscale_CNN_x2_M.glsl'))
MAX_INPUTS = 8
INPUT = -1  # the model's input in a pass's input list

HEADER = '''#version 450
// Generated by tools/anime4k.py from {source} (Anime4K v4.0.1, MIT, bloc97):
// {desc}
layout(local_size_x = 8, local_size_y = 8) in;
layout(set = 0, binding = 0, rgba16f) uniform writeonly image2D out_image;
layout(set = 0, binding = 1) uniform sampler bilinear;
{textures}
layout(push_constant) uniform Constants {{ uint linear; }} pc;

vec4 encode(vec4 c) {{ // linear light to sRGB
    if (pc.linear == 0u) return c;
    vec3 v = max(c.rgb, 0.0);
    return vec4(mix(v * 12.92, 1.055 * pow(v, vec3(1.0 / 2.4)) - 0.055, step(0.0031308, v)), c.a);
}}
vec4 decode(vec4 c) {{ // sRGB to linear light
    if (pc.linear == 0u) return c;
    vec3 v = max(c.rgb, 0.0);
    return vec4(mix(v / 12.92, pow((v + 0.055) / 1.055, vec3(2.4)), step(0.04045, v)), c.a);
}}

vec2 pos;
{macros}
'''

FOOTER = '''
void main() {{
    const ivec2 at = ivec2(gl_GlobalInvocationID.xy), size = imageSize(out_image);
    if (any(greaterThanEqual(at, size))) {{
        return;
    }}
    pos = (vec2(at) + 0.5) / vec2(size);
    imageStore(out_image, at, {store});
}}
'''


def parse(text):
    """The passes of an mpv shader file: directives and the GLSL after them."""
    passes = []
    for block in re.split(r'(?m)^(?=//!DESC )', text)[1:]:
        directives, body = {}, []
        for line in block.splitlines():
            if line.startswith('//!'):
                key, _, value = line[3:].partition(' ')
                directives.setdefault(key, []).append(value.strip())
            else:
                body.append(line)
        passes.append((directives, '\n'.join(body).strip() + '\n'))
    return passes


def scale_of(expression, scales):
    """The size of a //!WIDTH or //!HEIGHT in RPN (`conv2d_tf.w 2 *`) as a multiple of the input."""
    stack = []
    for token in expression.split():
        if token == '*':
            b, a = stack.pop(), stack.pop()
            stack.append(a * b)
        elif token[-2:] in ('.w', '.h'):
            stack.append(scales[token[:-2]])
        else:
            stack.append(int(token))
    (value,) = stack
    return value


def model(name, file, out):
    """Writes the model's shaders; returns its table entries (symbol, scale, inputs, output)."""
    passes, entries = parse((SOURCE / file).read_text()), []
    producer, scales = {'MAIN': INPUT}, {'MAIN': 1}
    for index, (d, body) in enumerate(passes):
        binds, (save,) = d['BIND'], d['SAVE']
        assert 'HOOKED' not in body and len(binds) <= MAX_INPUTS, (file, index)
        scale = scale_of(d['WIDTH'][0], scales)
        assert scale == scale_of(d['HEIGHT'][0], scales), (file, index)
        textures, macros, inputs = [], [], []
        for k, bound in enumerate(binds):
            source = producer[bound]
            read = 'encode(texture(sampler2D(t{k}, bilinear), (p)))' if source == INPUT \
                else 'texture(sampler2D(t{k}, bilinear), (p))'
            textures.append(f'layout(set = 0, binding = {2 + k}) uniform texture2D t{k};')
            macros += [f'#define {bound}_size vec2(textureSize(sampler2D(t{k}, bilinear), 0))',
                       f'#define {bound}_pt (1.0 / {bound}_size)',
                       f'#define {bound}_pos pos',
                       f'#define {bound}_tex(p) ' + read.format(k=k),
                       f'#define {bound}_texOff(o) {bound}_tex(pos + (o) * {bound}_pt)']
            inputs.append(source)
        last = save == 'MAIN'
        assert last == (index == len(passes) - 1), (file, index)
        shader = f'{name}_{index}.comp'
        (out / shader).write_text(
            HEADER.format(source=file, desc=d['DESC'][0], textures='\n'.join(textures),
                          macros='\n'.join(macros)) + '\n' + body +
            FOOTER.format(store='decode(hook())' if last else 'hook()'))
        producer[save], scales[save] = index, scale
        entries.append((f'anime4k_{name}_{index}_comp', scale, inputs, shader))
    return entries


def main(out=OUT, table=TABLE):
    """Writes the shaders and shaders.cmake into out, the pass table to table."""
    out.mkdir(exist_ok=True)
    for old in out.glob('*.comp'):
        old.unlink()
    tables, cmake = [], []
    for name, file in MODELS:
        entries = model(name, file, out)
        rows = []
        for symbol, scale, inputs, shader in entries:
            cmake.append(f'add_host_shader(anime4k/{shader} {symbol})')
            listed = ', '.join(map(str, inputs + [INPUT] * (MAX_INPUTS - len(inputs))))
            rows.append(f'    {{{symbol.upper()}, {scale}, {len(inputs)}, {{{listed}}}}},')
        tables.append(f'// {file}\ninline constexpr Anime4kShader {name.upper()}[] = {{\n' + '\n'.join(rows) + '\n};')
    (out / 'shaders.cmake').write_text('# Generated by tools/anime4k.py.\n' + '\n'.join(cmake) + '\n')
    includes = '\n'.join(f'#include "shaders/{line.split()[1][:-1]}.h"' for line in cmake)
    table.write_text(f'''// SPDX-License-Identifier: GPL-2.0-or-later
// Generated by tools/anime4k.py: the passes of the Anime4K models (gpu/third_party/anime4k).
#pragma once

#include <cstdint>
#include <span>

{includes}

namespace Platform {{

// A pass reads up to 8 textures (-1: the model's input, else an earlier pass's output) and
// writes one, `scale` times the input's size. The last pass's output is the model's.
struct Anime4kShader {{
    std::span<const uint32_t> code;
    uint32_t scale;
    uint32_t input_count;
    int8_t inputs[{MAX_INPUTS}];
}};

{chr(10).join(tables)}

}} // namespace Platform
''')
    return len(cmake)


if __name__ == '__main__':
    print(f'{main()} passes from {len(MODELS)} models')
